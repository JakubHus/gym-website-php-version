            <h2>FAQ - Najczęściej zadawane pytania</h2>
            <h3>1. W jakich godzinach otwarcia funkcjonuje siłownia?</h3>
            <p>Wszystkie nasze kluby są otwarte przez 7 dni w tygodniu w godzinach: 6:30 - 23:00 (godziny otwarcia w święta mogą się różnić od tradycyjnych).</p>
            
            <h3>2. Jak zakupić karnet do klubu/klubów?</h3>
            <p>W celu dokonania zakupu karnetu należy przejść bezpośrednio ze strony głównej EnerGym w zakładkę "Karnety" i postępować wg dalszych instrukcji i informacji. Można również skorzystać z formy telefonicznej lub zakupić karnet stacjonarnie w wybranym klubie.</p>
            
            <h3>3. Czy mogę zamrozić karnet na czas nieokreślony?</h3>
            <p>Zakupione karnety są ważne przez miesiąc od daty zakupu. Zamrożenie karnetu jest opcją dostępną tylko dwa razy w roku kalendarzowym oraz na maksymalnie dwa tygodnie (bez opłat). W przypadku dłuższego zamrożenia, klient zobowiązany jest wnieść dodatkową opłatę w wysokości 30 zł za odmrożenie karnetu do końca okresu rozliczeniowego.</p>
            
            <h3>4. Czy mogę zwrócić karnet?</h3>
            <p>Nie, zakupione karnety są niemożliwe do zwrócenia, a tym samym - opłata za niego jest bezzwrotna. Prosimy o dokonywanie przemyślanych zakupów.</p>
            
            <h3>5. Jakie zajęcia grupowe są dostępne w ramach karnetów?</h3>
            <p>W Karnecie Basic zajęcia grupowe nie zawierają się w jego cenie - jeśli klient chce na takie uczęszczać, musi dokonać oddzielnego zapisu i zakupu. W przypadku Karnetu Standard - klient ma możliwość zapisu na jedne wybrane zajęcia grupowe w cenie karnetu. W przypadku Karnetu Premium - można uczęszczać na wszystkie zajęcia bez dodatkowych opłat.</p>
            
            <h3>6. Czy w klubach są szafki na klucz?</h3>
            <p>Tak, we wszystkich naszych klubach są szafki na klucz, który klient dostaje każdorazowo na recepcji przy wejściu na siłownię.</p>
            
            <h3>7. Czy mogę kupić na siłowni wodę bądź suplementy?</h3>
            <p>Tak, wszystkie kluby posiadają na recepcji szeroką gamę suplementów oraz napojów.</p>
